def host_label(u):
    m = re.match(r"https?://([^/]+)(/[^#?]*)?", u)
    h = m.group(1).replace("www.", "")
    p = (m.group(2) or "").rstrip("/")
    return h + (p if p and len(p) < 18 else ("/…" if p else ""))

def build(D, ROOT):
    esc = lambda s: html.escape(s, quote=True)
    ver = D["version"]
    os.makedirs(os.path.join(ROOT, "public", "ghf-lang"), exist_ok=True)
    open(os.path.join(ROOT, "public", "ghf-lang", "ghf-theme.css"), "w", encoding="utf-8").write(THEME_CSS.replace("__VER__", ver))
    rows = []
    for s in D["stops"]:
        P, S = s.get("colors") or ("#0A0A0A", "#F2C94C")
        ext = not s["url"].startswith("https://bucklerfamily.estate/")
        rows.append(
            f'<li><details name="sites" style="--p:{P};--s:{S}">'
            f'<summary><span class="num">{s["n"]:02d}</span><i class="dot" aria-hidden="true"></i>'
            f'<span class="t"><b>{esc(s["title"])}</b><small>{esc(s["tag"])}</small></span><span class="chev" aria-hidden="true"></span></summary>'
            f'<div class="body"><p>{esc(s.get("desc") or s["caption"])}</p>'
            f'<a class="visit" href="{esc(s["url"])}">{GLOBE}<span class="v">Visit</span><span class="h">{esc(host_label(s["url"]))}</span><span aria-hidden="true">{"↗" if ext else "→"}</span></a>'
            f'<p class="hue" aria-hidden="true"><i style="background:{P}"></i><i style="background:{S}"></i></p></div></details></li>')
    page = PAGE.replace("__ROWS__", "\n".join(rows)).replace("__N__", str(len(D["stops"]))).replace("__VER__", ver)
    os.makedirs(os.path.join(ROOT, "public", "1d"), exist_ok=True)
    open(os.path.join(ROOT, "public", "1d", "index.html"), "w", encoding="utf-8").write(page)
    est = json.load(open(os.path.join(ROOT, "public", "ghf-lang", "sites", "estate.json"), encoding="utf-8"))
    d = {k: v for k, v in est.items() if k not in ("strings", "patterns")}
    d.update({"site": "basecamp1d", "mount": "#lang-slot", "mountMode": "append", "patterns": [],
              "strings": {k: {"cy": v[0], "es": v[1]} for k, v in TR.items()},
              "note": "Cedwyn Estate 1D view (bucklerfamily.estate/1d/): interface strings, site names and tags. Descriptions stay in English, the authoritative text. Generated by campus/build_basecamp.py."})
    for k in ("fixedBelow", "fixed", "inlineStyle"): d.pop(k, None)
    json.dump(d, open(os.path.join(ROOT, "public", "ghf-lang", "sites", "basecamp1d.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    return len(page)

